CN_DIGITS: dict[str, int] = {
    "零": 0, "一": 1, "二": 2, "两": 2, "三": 3, "四": 4,
    "五": 5, "六": 6, "七": 7, "八": 8, "九": 9, "十": 10,
}

#: 整段说法 → 数值。用于「二连击」「三次」这类没有阿拉伯数字的写法。
CN_NUMERALS: dict[str, int] = {
    **CN_DIGITS,
    "十一": 11, "十二": 12, "十三": 13, "十四": 14, "十五": 15,
    "十六": 16, "十七": 17, "十八": 18, "十九": 19,
    "二十": 20, "三十": 30, "五十": 50,
}

_ARABIC = re.compile(r"[-+]?\d+(?:\.\d+)?")


def parse_number(text: str) -> float | None:
    """从一段文本里取出数值，支持阿拉伯数字与中文数字。

    描述里两种写法都会出现，而且**必须都支持**：

        「攻击变为5连射」    → 5
        「攻击变为二连击」  → 2      ← 只有中文数字
        「并连续攻击三次」  → 3
        「攻击间隔缩短(-0.22)」 → -0.22
    """
    if not text:
        return None

    match = _ARABIC.search(text)
    if match:
        try:
            return float(match.group())
        except ValueError:
            return None

    # 中文数字：从长到短匹配，避免「十二」被「十」截断
    for word in sorted(CN_NUMERALS, key=len, reverse=True):
        if word in text:
            return float(CN_NUMERALS[word])
    return None


def find_attribute(text: str) -> str | None:
    """在文本里找出属性概念。长词优先，避免「攻击」抢走「攻击速度」。"""
    best_key, best_len = None, 0
    for key, words in ATTRIBUTES.items():
        for word in words:
            if word in text and len(word) > best_len:
                best_key, best_len = key, len(word)
    return best_key


def find_relation(text: str) -> str | None:
    """在文本里找出关系概念。长词优先，避免「提高」抢走「提高至」。"""
    best_key, best_len = None, 0
    for key, words in RELATIONS.items():
        for word in words:
            if word in text and len(word) > best_len:
                best_key, best_len = key, len(word)
    return best_key


def find_irrelevant(text: str) -> str | None:
    """判断文本是否是「已知与非伤害无关」的概念，返回概念名或 None。"""
    for concept, (keywords, _reason) in IRRELEVANT.items():
        for keyword in keywords:
            if keyword in text:
                return concept
    return None


#: 这些属性一旦出现，就说明该片段**可能影响 DPS**。
#: 用来给未识别片段做风险分级——不相关的就不报警。
#:
#: 注意 ``defense`` 与 ``res`` **没有**列在这里：它们要分两种情况——
#:   * 「无视N点法术抗性」→ 说的是**敌人**的抗性 → 影响伤害
#:   * 「防御力+100%」     → 说的是**干员自己**的防御 → 与输出无关
#: 只看属性词分不出来，必须结合关系词，所以判定放在识别器里做。
